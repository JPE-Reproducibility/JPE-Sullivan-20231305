assign.brand <- function(df, brand.name, brand.pattern, restaurant.var = 'restaurant'){
    idx <- grep(brand.pattern, df[, restaurant.var], ignore.case = TRUE)
    df$brand[idx] <- brand.name
    return(df)
}

